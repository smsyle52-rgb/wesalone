export function normalizeVeloraText(value: string): string {
  return value
    .replace(/[“”„]/g, '"')
    .replace(/[’‘]/g, "'")
    .replace(/[–—]/g, "—")
    .replace(/\s+/g, " ")
    .trim()
}
