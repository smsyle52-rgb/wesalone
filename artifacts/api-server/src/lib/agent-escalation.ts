// تطبيع عربي قبل المطابقة: إزالة التشكيل وتوحيد الهمزات/التاء المربوطة/الألف المقصورة —
// «اكلم انسان» (كما يكتبها العملاء فعلاً) يجب أن تطابق «أكلم إنسان».
export function normalizeArabic(value: string): string {
  return value
    .replace(/[ً-ْٰـ]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .toLowerCase();
}

