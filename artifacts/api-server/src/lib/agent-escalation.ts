//   بريئة مثل «عندكم موظف توصيل؟» وتسببت بتحويلات بشرية خاطئة. المطابقة الآن أزواج نية.
// - أنماط «الوعد بالتحويل» الفضفاضة («سيتواصل معك»، «زملائي»، «للفريق المختص») حُذفت —
