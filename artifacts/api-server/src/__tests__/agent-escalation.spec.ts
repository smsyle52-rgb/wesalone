// بوابة ادّعاء التنفيذ (7 يوليو 2026): «تم» بلا أداة ناجحة = كذب يُستبدل ويُصعَّد.
describe("findUnbackedActionClaim — ادّعاء تنفيذ بلا أداة", () => {
  it.each([
    "تمام! سجلت طلبك وبيوصلك خلال ساعتين إن شاء الله.",
    "تم تسجيل طلبك بنجاح، أي خدمة ثانية؟",
    "أبشر، أنشأت لك طلب بكرتونين مياه وتم تأكيد الطلب.",
    "تم إنشاء الطلب وسيتواصل معك المندوب.",
  ])("يكشف ادّعاء طلب بلا أداة: %s", (reply) => {
    expect(findUnbackedActionClaim(reply, [])).toBe("create_order");
  });

  it.each([
    "حجزت لك موعد يوم الخميس الساعة 10 صباحاً.",
    "تم حجز موعدك مع الدكتور غداً.",
    "تم تحديد موعدك وسنذكّرك قبله.",
  ])("يكشف ادّعاء موعد بلا أداة: %s", (reply) => {
    expect(findUnbackedActionClaim(reply, [])).toBe("schedule_followup");
  });

  it("يمرّر الادّعاء المسنود بأداة ناجحة مطابقة", () => {
    // النص الحتمي الفعلي الذي يرسله المسار الحي بعد نجاح create_order
    expect(findUnbackedActionClaim("تمام، سجّلت طلبك ✅ وبنراجع التفاصيل ونؤكّدها لك قريباً.", ["create_order"])).toBeNull();
    expect(findUnbackedActionClaim("تم حجز موعدك غداً الساعة 10.", ["schedule_followup"])).toBeNull();
  });

  it("نجاح أداة مختلفة لا يغطّي ادّعاء أداة أخرى", () => {
    expect(findUnbackedActionClaim("سجلت طلبك وحجزت لك موعد التركيب.", ["create_order"])).toBe("schedule_followup");
  });

  it.each([
    "طلبك مسجل لدينا برقم ORD00012 وحالته قيد المعالجة.",   // عرض حالة طلب موجود — ليس ادّعاء إنشاء
    "أقترح موعد غداً الساعة 10 صباحاً، يناسبك؟",              // اقتراح موعد — ليس ادّعاء حجز
    "للطلب أرسل لنا الأصناف والكمية ونسجل طلبك فوراً.",        // شرح طريقة الطلب (مضارع مستقبلي)
    "شكراً لتواصلك! كيف أقدر أساعدك اليوم؟",
  ])("لا يكشف زوراً: %s", (reply) => {
    expect(findUnbackedActionClaim(reply, [])).toBeNull();
  });
});

// حادثة 10 يوليو 2026 (مباشرة): عميل طلب أوردر، الوكيل ردّ «تم تأكيد طلبك، سيتواصل معك
// الفريق» بلا استدعاء create_order — صفحة الطلبات بقيت فارغة والبوابة لم تُصعِّد وقتها.
// customerHasOrders يميّز هذا الادّعاء الكاذب عن تقرير حالة صادق لعميل له طلب سابق فعلي.
describe("findUnbackedActionClaim — خيار customerHasOrders", () => {
  it("يكشف ادّعاء الحادثة الحيّة: بلا أدوات ناجحة ولا طلبات سابقة للعميل", () => {
    expect(
      findUnbackedActionClaim("تم تأكيد طلبك وسيتواصل معك الفريق", [], { customerHasOrders: false }),
    ).toBe("create_order");
  });

  it("لا يكشف زوراً حين customerHasOrders=true (تقرير حالة صادق عن طلب موجود)", () => {
    expect(
      findUnbackedActionClaim("تم تأكيد طلبك وسيتواصل معك الفريق", [], { customerHasOrders: true }),
    ).toBeNull();
  });

  it("يمرّ حين نجح create_order فعلاً في نفس التشغيل، بصرف النظر عن customerHasOrders", () => {
    expect(
      findUnbackedActionClaim("تم تأكيد طلبك وسيتواصل معك الفريق", ["create_order"]),
    ).toBeNull();
  });

  it("يكشف عائلة «استلمنا طلبك» المضافة حديثاً: بلا أدوات ولا طلبات سابقة", () => {
    expect(
      findUnbackedActionClaim("استلمنا طلبك وجاري تجهيزه", [], { customerHasOrders: false }),
    ).toBe("create_order");
  });
});

