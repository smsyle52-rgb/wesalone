import { describe, expect, it } from "vitest";
import { includesEscalationKeyword, normalizeArabic, replyPromisesHandoff } from "../lib/agent-escalation";

// حالات مأخوذة من أدلة إنتاج حقيقية (3 يوليو 2026) — ضبط دقة التصعيد البشري:
// التصعيد الناقص وعدٌ مكسور، والتصعيد الزائد يقتل الأتمتة. كلاهما عطل.

describe("normalizeArabic", () => {
  it("توحّد الهمزات والتاء المربوطة والألف المقصورة", () => {
    expect(normalizeArabic("أكلم إنسان")).toBe("اكلم انسان");
    expect(normalizeArabic("خدمة العملاء")).toBe("خدمه العملاء");
    expect(normalizeArabic("شكوى")).toBe("شكوي");
  });
});

describe("includesEscalationKeyword — طلب العميل", () => {
  it.each([
    "حولني لشخص حقيقي",            // الحالة الحيّة من محادثة 76f46765
    "ابغى اكلم موظف",
    "أبغى أكلم إنسان",              // بهمزات — يجب أن يلتقطها التطبيع
    "اريد موظف يرد علي",
    "عندي شكوى على الخدمة",
    "ابغي الغاء الطلب",
    "كلمني انسان مو بوت",
    "وصلوني بخدمة العملاء",
  ])("يصعّد: %s", (message) => {
    expect(includesEscalationKeyword(message)).toBe(true);
  });

  it.each([
    "عندكم موظف توصيل يجي البيت؟",   // «موظف» بريئة — كانت تصعّد خطأً قبل الضبط
    "كم سعر الموظف الذكي شهرياً؟",   // اسم المنتج نفسه فيه «موظف»
    "من المسؤول عن التوصيل عندكم؟",  // «مسؤول» بريئة
    "ابي اسوي تحويل بنكي للدفع",     // «تحويل» مالية لا بشرية
    "هل البشرية استفادت من الذكاء؟",  // «بشري» داخل كلمة أخرى
    "متى يفتح المحل؟",
  ])("لا يصعّد: %s", (message) => {
    expect(includesEscalationKeyword(message)).toBe(false);
  });
});

describe("replyPromisesHandoff — ادّعاء الوكيل", () => {
  it.each([
    "لقد قمت بتحويل طلبك إلى الفريق المختص وسيتواصلون معك في أقرب وقت.", // الادعاء الحيّ من الإنتاج
    "سأحول طلبك الآن لأحد الزملاء.",
    "سأقوم بتحويل طلبك إلى الفريق للتأكد من الأسعار.",
    "تم تحويل المحادثة لموظف مختص.",
    "سيتم نقل طلبك للقسم المعني.",
    // حادثة 4 يوليو 2026 — عائلة «صعّد» (نفس الادعاء بمفردة مختلفة، من محادثة حقيقية)
    "سأقوم بتصعيد طلبك للإدارة لمراجعته والتواصل معك بخصوص فرص الشراكة أو الاستثمار المتاحة.",
    "سأقوم بتضمين طلبك هذا مع طلبك السابق بخصوص فرص الشراكة، وسأصعد كلا الأمرين للإدارة لمراجعتهما والتواصل معك.",
    "تم تصعيد طلبك للإدارة المختصة.",
  ])("يصعّد (الوعد = تنفيذ): %s", (reply) => {
    expect(replyPromisesHandoff(reply)).toBe(true);
  });

  it.each([
    "المندوب سيتواصل معك لتأكيد عنوان التوصيل.",   // تنسيق توصيل عادي — كانت تصعّد خطأً
    "زملائي في الفريق جاهزون لخدمتك في أي وقت.",
    "سيرد عليك أحد ممثلينا عبر البريد خلال يومين.",
    "شكراً لتواصلك معنا! كيف أقدر أساعدك؟",
    "فريقنا المختص يعمل على تجهيز طلبك.",
    // حادثة 3 يوليو (b044a0d5): وصفُ المنتج نفسه — ذُكرت فيه «خدمة العملاء» فطابق
    // قائمة كلمات العميل التي كانت تُفحص خطأً على ردّ الوكيل، وحُوّلت المحادثة
    // بشرياً بصمت وبقي العميل بلا ردّ 3.5 ساعات. ردّ الوكيل يُفحص بهذه الدالة فقط.
    "أهلاً بك! وصال ون هي منصة عربية لإدارة محادثات العملاء والمبيعات وخدمة العملاء من لوحة واحدة. تجمع القنوات المدعومة، تنظّم المحادثات، وتشغّل وكلاء ذكاء اصطناعي.",
    "نوفر لك دعم فني على مدار الساعة وخدمة عملاء مميزة ضمن كل الباقات.",
  ])("لا يصعّد: %s", (reply) => {
    expect(replyPromisesHandoff(reply)).toBe(false);
  });
});
